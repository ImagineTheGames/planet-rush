/** What a tap on the codex resolves to. */
export type CodexTarget =
  | { readonly kind: 'back' }
  | { readonly kind: 'tab'; readonly index: number }
  | { readonly kind: 'entry'; readonly index: number };

/**
 * The target a tap at `(x, y)` hits, or null. `railScroll` is how far the entry
 * rail has been scrolled down (view state, default 0): each entry's on-screen
 * rect is its layout rect shifted up by that offset, and a hit only counts if it
 * also falls inside the rail's clip rect — a title scrolled out of view is not
 * tappable, the same "invisible is untappable" rule the menus keep.
 *
 * Order matters: BACK and the tabs sit above the rail and are tested first, so a
 * rail that happens to extend under them can never steal their taps.
 */
export function codexHitTest(layout: CodexLayout, x: number, y: number, railScroll = 0): CodexTarget | null {
  if (hitRect(layout.back, x, y)) return { kind: 'back' };
  for (let i = 0; i < layout.tabs.length; i++) {
    const rect = layout.tabs[i];
    if (rect && hitRect(rect, x, y)) return { kind: 'tab', index: i };
  }
  // Entries: only within the rail viewport, shifted by the scroll offset.
  if (!hitRect(layout.rail, x, y)) return null;
  for (let i = 0; i < layout.railEntries.length; i++) {
    const rect = layout.railEntries[i];
    if (!rect) continue;
    const shifted: Rect = { x: rect.x, y: rect.y - railScroll, width: rect.width, height: rect.height };
    if (hitRect(shifted, x, y)) return { kind: 'entry', index: i };
  }
  return null;
}

/**
 * A stable string naming one codex control — `tab:2`, `entry:7`, `back`.
 *
 * The pointer layer needs to say "the finger is on THIS control" without holding
 * a rect, and both the hover cue (`src/main.ts`) and the plate's rest/hover/press
 * state ({@link codexModel}) ask the same question. Stating the key format once,
 * beside the target it names, is what keeps the two from drifting into two
 * spellings of one control — the same discipline `./lobby-geometry`
 * `entryTargetKey` keeps for the doors.
 */
export function codexTargetKey(target: CodexTarget | null): string | null {
  if (!target) return null;
  return target.kind === 'back' ? 'back' : `${target.kind}:${target.index}`;
}

