// ---------------------------------------------------------------------------
// Lobby reuse (GDD §2.10 point 2) — the same data, where the lobby answers a
// live question
// ---------------------------------------------------------------------------
//
// "The lobby reuses the same data … bot dossier on long-press/hover of a bot
// slot's name; hull description on the ship-class picker. Small, non-blocking,
// dismissible." These resolve a lobby row to its codex entry and hand back a
// compact hint — the same data the CODEX screen draws in full, trimmed to a
// tooltip. Pure lookups; the tooltip's gesture (long-press / hover) and its draw
// are the lobby view's and `src/main.ts`'s, off this seam.
//
// The keys line up by construction: a bot's personality id is the lowercased
// character name and the codex id is `bots-<id>` (`bots-rusty`); a hull's
// {@link ShipClass} value is the codex id's tail (`ship-interceptor`). Both
// resolvers are total — an unknown key returns null, so a future character with
// no codex entry yet simply shows no tooltip rather than crashing the row.

/** A compact codex reference for a lobby tooltip: a title, the one-line summary,
 *  and any difficulty/hull badges. Deliberately smaller than a full detail —
 *  "small, non-blocking, dismissible". */
export interface CodexHint {
  readonly title: string;
  readonly summary: string;
  readonly badges: readonly string[];
}

function hintFor(entry: CodexEntry | undefined): CodexHint | null {
  if (!entry) return null;
  const badges: string[] = [];
  if (entry.difficulty) badges.push(entry.difficulty);
  if (entry.hull) badges.push(entry.hull);
  return { title: entry.title, summary: entry.summary, badges };
}

/** The codex dossier for a lobby bot, by its personality id (or its display name
 *  — the two differ only in case). Null for a character with no entry. */
export function codexBotHint(data: CodexData, personality: string): CodexHint | null {
  const id = `bots-${personality.toLowerCase()}`;
  return hintFor(data.bots.entries.find((e) => e.id === id));
}

/** The codex hull description for the ship-class picker, by class. Null if the
 *  ships file has no entry for it. `shipClass` is a {@link ShipClass} value, e.g.
 *  `'interceptor'`. */
export function codexShipHint(data: CodexData, shipClass: string): CodexHint | null {
  return hintFor(data.ships.entries.find((e) => e.id === `ship-${shipClass}`));
}
