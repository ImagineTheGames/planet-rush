/**
 * src/ui/codex.ts — the CODEX reference screen. OWNER: Gameplay Engineer
 * (content/codex/ + this screen, brief c1-codex-screen; GDD §2.10).
 *
 * The optional main-menu reference a player consults voluntarily — "never a gate
 * before play" (GDD §2.10, verbatim). Five tabs (OBJECTIVE / BOTS / SHIPS /
 * SYSTEMS / STRATEGY) over the five `content/codex/*.json` files: a scrollable list of
 * entry titles on the left, the selected entry's detail on the right — its
 * summary, its body, the machine-checked `facts[]` (the numbers
 * `tests/codex/codex-constants.test.ts` pins to `src/sim/constants.ts`), any
 * difficulty/hull badges, and its cross-references. A BACK button leaves.
 *
 * Same three-piece discipline as every screen in this directory: a pure, DOM-free
 * model with its layout co-located, plus a thin Pixi view ({@link ./codex-view})
 * that draws exactly what this returns and decides nothing. Nothing here imports
 * PixiJS, so the whole screen unit-tests headless.
 *
 * **The data is handed in, not imported.** `content/codex/` lives outside `src/`
 * (it is regenerated by the codex pipeline, not compiled), so the model takes the
 * five parsed files as a value — `createCodex(normalizeCodex(files))` — exactly
 * as `lobbyModel` takes a `LobbyState`. Whoever boots the client
 * (`src/main.ts`) imports the JSON (Vite resolves it) and hands it over; the
 * tests load it off disk with `readFileSync`. So this file never reaches across
 * the compile boundary, and a malformed entry is normalised away here rather than
 * crashing a draw.
 *
 * **Scrolling lives in the view, not the model.** The entry rail (SYSTEMS has
 * fourteen entries) and a long body both scroll vertically; that offset is view
 * state. The one place the model must know about it is the hit test — a tap on a
 * scrolled rail lands on a different entry — so {@link codexHitTest} takes the
 * rail's scroll offset as a scalar and keeps the entry geometry pure and here,
 * rather than leaking it into the view.
 */

